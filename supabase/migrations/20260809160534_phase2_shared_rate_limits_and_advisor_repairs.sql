-- Phase 2 shared rate limiting and narrowly scoped advisor remediations.
--
-- This migration is intentionally forward-only. Rehearse it against a
-- production-compatible isolated database before staging or production.

create schema if not exists private;

create table if not exists private.api_rate_limit_buckets (
  scope text not null,
  identity_hash text not null,
  window_started_at timestamptz not null,
  request_count integer not null,
  expires_at timestamptz not null,
  updated_at timestamptz not null default timezone('utc', now()),
  constraint api_rate_limit_buckets_pkey
    primary key (scope, identity_hash, window_started_at),
  constraint api_rate_limit_buckets_scope_check
    check (scope ~ '^[a-z0-9][a-z0-9_.:-]{0,63}$'),
  constraint api_rate_limit_buckets_identity_hash_check
    check (identity_hash ~ '^[0-9a-f]{64}$'),
  constraint api_rate_limit_buckets_request_count_check
    check (request_count > 0),
  constraint api_rate_limit_buckets_expiry_check
    check (expires_at > window_started_at)
);

create index if not exists api_rate_limit_buckets_expiry_idx
  on private.api_rate_limit_buckets (expires_at);

alter table private.api_rate_limit_buckets enable row level security;
revoke all on table private.api_rate_limit_buckets
  from public, anon, authenticated, service_role;

create or replace function public.consume_public_rate_limit(
  p_scope text,
  p_key_hash text,
  p_window_seconds integer,
  p_limit integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := pg_catalog.clock_timestamp();
  v_window_started_at timestamptz;
  v_expires_at timestamptz;
  v_request_count integer;
begin
  if p_scope is null
    or p_scope !~ '^[a-z0-9][a-z0-9_.:-]{0,63}$' then
    raise exception using
      errcode = '22023',
      message = 'Invalid rate-limit scope.';
  end if;

  if p_key_hash is null
    or p_key_hash !~ '^[0-9a-f]{64}$' then
    raise exception using
      errcode = '22023',
      message = 'Invalid rate-limit identity.';
  end if;

  if p_window_seconds is null
    or p_window_seconds < 1
    or p_window_seconds > 86400 then
    raise exception using
      errcode = '22023',
      message = 'Rate-limit window must be between 1 and 86400 seconds.';
  end if;

  if p_limit is null or p_limit < 1 or p_limit > 100000 then
    raise exception using
      errcode = '22023',
      message = 'Rate limit must be between 1 and 100000.';
  end if;

  v_window_started_at := pg_catalog.to_timestamp(
    pg_catalog.floor(
      extract(epoch from v_now) / p_window_seconds
    ) * p_window_seconds
  );
  v_expires_at := v_window_started_at
    + (p_window_seconds * interval '1 second');

  insert into private.api_rate_limit_buckets (
    scope,
    identity_hash,
    window_started_at,
    request_count,
    expires_at,
    updated_at
  )
  values (
    p_scope,
    p_key_hash,
    v_window_started_at,
    1,
    v_expires_at,
    v_now
  )
  on conflict (scope, identity_hash, window_started_at)
  do update
    set request_count = private.api_rate_limit_buckets.request_count + 1,
        expires_at = excluded.expires_at,
        updated_at = excluded.updated_at
  returning request_count into v_request_count;

  -- Active identities remove their own expired buckets. A small deterministic
  -- sample also bounds abandoned one-shot identities without a full-table
  -- cleanup on every public request.
  delete from private.api_rate_limit_buckets
  where scope = p_scope
    and identity_hash = p_key_hash
    and expires_at <= v_window_started_at;

  if pg_catalog.right(p_key_hash, 1) = '0' then
    delete from private.api_rate_limit_buckets bucket
    where bucket.ctid in (
      select expired.ctid
      from private.api_rate_limit_buckets expired
      where expired.expires_at < v_now
      order by expired.expires_at
      limit 200
    );
  end if;

  return pg_catalog.jsonb_build_object(
    'allowed', v_request_count <= p_limit,
    'limit', p_limit,
    'remaining', greatest(p_limit - v_request_count, 0),
    'reset_seconds', greatest(
      1,
      pg_catalog.ceil(extract(epoch from (v_expires_at - v_now)))::integer
    ),
    'reset_at', v_expires_at,
    'request_count', v_request_count
  );
end;
$$;

revoke all on function public.consume_public_rate_limit(text, text, integer, integer)
  from public, anon, authenticated, service_role;
grant execute on function public.consume_public_rate_limit(text, text, integer, integer)
  to service_role;

comment on table private.api_rate_limit_buckets is
  'Server-only shared fixed-window counters. Identities are keyed by an HMAC generated by the backend; raw client addresses are never stored.';
comment on function public.consume_public_rate_limit(text, text, integer, integer) is
  'Atomically consumes a shared API rate-limit token. Service-role only.';

-- The production advisor reports no primary key on public.pricelist. Its SKU
-- values were verified read-only before this migration was authored: 28,945
-- rows, zero nulls, and zero duplicates. Repeat that preflight in the target
-- transaction so a changed import fails closed instead of losing data.
do $$
declare
  v_primary_key_count integer;
  v_invalid_sku_count bigint;
begin
  if pg_catalog.to_regclass('public.pricelist') is null then
    return;
  end if;

  select count(*)
  into v_primary_key_count
  from pg_catalog.pg_constraint constraint_row
  where constraint_row.conrelid = 'public.pricelist'::pg_catalog.regclass
    and constraint_row.contype = 'p';

  if v_primary_key_count > 0 then
    if not exists (
      select 1
      from pg_catalog.pg_constraint constraint_row
      join pg_catalog.pg_attribute attribute_row
        on attribute_row.attrelid = constraint_row.conrelid
       and attribute_row.attnum = constraint_row.conkey[1]
      where constraint_row.conrelid = 'public.pricelist'::pg_catalog.regclass
        and constraint_row.contype = 'p'
        and pg_catalog.array_length(constraint_row.conkey, 1) = 1
        and attribute_row.attname = 'sku'
    ) then
      raise exception 'public.pricelist already has an unexpected primary key';
    end if;

    return;
  end if;

  select count(*)
  into v_invalid_sku_count
  from (
    select pricelist_row.sku
    from public.pricelist pricelist_row
    group by pricelist_row.sku
    having pricelist_row.sku is null or count(*) > 1
  ) invalid_skus;

  if v_invalid_sku_count > 0 then
    raise exception
      'public.pricelist contains % null or duplicate SKU groups; primary key not added',
      v_invalid_sku_count;
  end if;

  alter table public.pricelist
    alter column sku set not null;
  alter table public.pricelist
    add constraint pricelist_pkey primary key (sku);
end;
$$;

-- Preserve the existing service-role-only meaning while removing a per-row
-- auth.role() evaluation flagged by the advisor.
do $$
declare
  v_existing_policy_count integer;
  v_expected_policy_count integer;
begin
  if pg_catalog.to_regclass('catalog.admin_notifications') is null then
    return;
  end if;

  select count(*)
  into v_existing_policy_count
  from pg_catalog.pg_policies policy_row
  where policy_row.schemaname = 'catalog'
    and policy_row.tablename = 'admin_notifications'
    and policy_row.policyname = 'service_role_admin_notifications_all';

  select count(*)
  into v_expected_policy_count
  from pg_catalog.pg_policies policy_row
  where policy_row.schemaname = 'catalog'
    and policy_row.tablename = 'admin_notifications'
    and policy_row.policyname = 'service_role_admin_notifications_all'
    and (
      (
        policy_row.cmd = 'ALL'
        and policy_row.roles = array['public']::name[]
        and policy_row.qual like '%auth.role()%service_role%'
        and policy_row.with_check like '%auth.role()%service_role%'
      )
      or (
        policy_row.cmd = 'ALL'
        and policy_row.roles = array['service_role']::name[]
        and policy_row.qual = 'true'
        and policy_row.with_check = 'true'
      )
    );

  if v_existing_policy_count <> v_expected_policy_count then
    raise exception
      'catalog.admin_notifications has an unexpected service-role policy; refusing automatic replacement';
  end if;

  drop policy if exists service_role_admin_notifications_all
    on catalog.admin_notifications;
  create policy service_role_admin_notifications_all
    on catalog.admin_notifications
    for all
    to service_role
    using (true)
    with check (true);
end;
$$;

-- `customers_internal_all` overlaps `customers_self_select` for SELECT. Split
-- internal writes by command and retain one SELECT policy with the same OR
-- semantics. The strict shape check prevents changing an unknown policy set.
do $$
declare
  v_legacy_policy_count integer;
  v_replacement_policy_count integer;
begin
  if pg_catalog.to_regclass('operations.customers') is null then
    return;
  end if;

  select count(*)
  into v_legacy_policy_count
  from pg_catalog.pg_policies policy_row
  where policy_row.schemaname = 'operations'
    and policy_row.tablename = 'customers'
    and policy_row.permissive = 'PERMISSIVE'
    and policy_row.roles = array['authenticated']::name[]
    and (
      (
        policy_row.policyname = 'customers_internal_all'
        and policy_row.cmd = 'ALL'
        and policy_row.qual like '%private.is_internal_user()%'
        and policy_row.with_check like '%private.is_internal_user()%'
      )
      or (
        policy_row.policyname = 'customers_self_select'
        and policy_row.cmd = 'SELECT'
        and policy_row.qual like '%user_id = ( SELECT auth.uid()%'
        and policy_row.qual like '%private.is_internal_user()%'
      )
    );

  select count(*)
  into v_replacement_policy_count
  from pg_catalog.pg_policies policy_row
  where policy_row.schemaname = 'operations'
    and policy_row.tablename = 'customers'
    and policy_row.policyname in (
      'customers_select',
      'customers_internal_insert',
      'customers_internal_update',
      'customers_internal_delete'
    );

  if v_legacy_policy_count = 0 and v_replacement_policy_count = 4 then
    return;
  end if;

  if v_legacy_policy_count <> 2 or v_replacement_policy_count <> 0 then
    raise exception
      'operations.customers has an unexpected RLS policy shape; refusing automatic consolidation';
  end if;

  drop policy customers_internal_all on operations.customers;
  drop policy customers_self_select on operations.customers;

  create policy customers_select
    on operations.customers
    for select
    to authenticated
    using (
      user_id = (select auth.uid())
      or (select private.is_internal_user())
    );

  create policy customers_internal_insert
    on operations.customers
    for insert
    to authenticated
    with check ((select private.is_internal_user()));

  create policy customers_internal_update
    on operations.customers
    for update
    to authenticated
    using ((select private.is_internal_user()))
    with check ((select private.is_internal_user()));

  create policy customers_internal_delete
    on operations.customers
    for delete
    to authenticated
    using ((select private.is_internal_user()));
end;
$$;
